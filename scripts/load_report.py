"""Consolidated load-test report from results/raw/*.results.csv (+ diagnostics, meta). All stand-in (simulated).
    python -m scripts.load_report   -> report/load_test_report.md"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "results" / "raw"


def superseded() -> set[str]:
    f = RAW / "SUPERSEDED.json"
    if not f.is_file():
        return set()
    d = json.loads(f.read_text(encoding="utf-8"))
    return set(d if isinstance(d, list) else d.keys())


def build() -> str:
    skip = superseded()
    rows = []
    for rf in sorted(RAW.glob("lt-*__*.results.csv")):
        run, scen = rf.name.split(".results.csv")[0].split("__", 1)
        if f"{run}__{scen}" in skip:
            continue
        r = pd.read_csv(rf)
        d = pd.read_csv(RAW / rf.name.replace(".results.csv", ".diagnostics.csv"))
        meta = json.loads((RAW / rf.name.replace(".results.csv", ".meta.json")).read_text(encoding="utf-8")) \
            if (RAW / rf.name.replace(".results.csv", ".meta.json")).is_file() else {}
        n = len(r)
        ok = r[r.status == "ok"]
        wall = meta.get("wall_elapsed_s") or float("nan")
        reasons = d.final_reason.value_counts().to_dict()
        rows.append(dict(run=run, scenario=scen, n=n, ok=len(ok), rl=int((r.status == "rate_limited").sum()),
                         to=int((r.status == "timeout").sum()), err=int((r.status == "error").sum()),
                         p50=ok.total_ms.median(), p95=ok.total_ms.quantile(.95),
                         retries=int(r.retries.sum()), thr=len(ok) / wall * 60 if wall == wall else float("nan"),
                         peakq=meta.get("peak_queue"), reasons=", ".join(f"{k}:{v}" for k, v in reasons.items())))
    out = ["# Load-test report (generated by scripts/load_report.py)", "",
           "**All rows are SIMULATED (local stand-in server, source=stand-in).** Latency/throughput are the stand-in's, "
           "calibrated from n=5 real Groq requests; rate limits, fault rates and the in-flight limit are assumptions. "
           "Superseded runs (SUPERSEDED.json) are excluded but kept on disk.", "",
           "| Run | Scenario | n | ok | rate_limited | timeout | error | p50 ms | p95 ms | Retries | ok/min | Peak queue | final reasons |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for x in rows:
        out.append(f"| {x['run']} | {x['scenario']} | {x['n']} | {x['ok']} | {x['rl']} | {x['to']} | {x['err']} | "
                   f"{x['p50']:.0f} | {x['p95']:.0f} | {x['retries']} | {x['thr']:.1f} | {x['peakq']} | {x['reasons']} |")
    out += ["", "Scenario coverage: steady, burst, overload, limit_halved (TPM/RPM exhaustion + 429 + Retry-After), "
            "daily_exhausted, retry_* (backoff comparison, depends on the UNVERIFIED count_rejected_rpm assumption), "
            "fault_5xx, fault_timeout, fault_incomplete, fault_mixed (provider failures). Recovery: the burst scenario's "
            "post-burst requests, plus `tests/test_recovery.py` (outage then success, reservation refund and settlement)."]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    p = ROOT / "report" / "load_test_report.md"
    p.write_text(build(), encoding="utf-8", newline="\n")
    print("wrote", p)
